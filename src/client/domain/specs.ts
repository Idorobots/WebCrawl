const circle = (radius: number) => ({ x: radius, y: radius });

// Object offsets and radii below stay unitless fractions of `size` in runtime
// state. Collision and rendering resolve them through object-geometry.ts.

const clip = (
  frames: readonly string[],
  sizeScale = 1,
  origin = { x: 0.5, y: 0.5 },
  frameDurationMs = 100,
  options: Pick<SpriteClip, "loop" | "holdLast" | "eventFrame" | "light"> = {},
): SpriteClip => ({ frames, sizeScale, origin, frameDurationMs, ...options });

const damageEffect = (sizeScale = 0.4): SpriteClip =>
  clip(EFFECT_FRAMES.damage, sizeScale, { x: 0.5, y: 0.5 }, 100, {
    light: { color: 0xff526b, radiusScale: 0.7, intensity: 1.15 },
  });
const explosionEffect = (sizeScale = 0.8): SpriteClip =>
  clip(EXPLOSION_FRAMES, sizeScale, { x: 0.5, y: 0.5 }, 1_000 / 12, {
    light: { color: 0xffa34d, radiusScale: 1.15, intensity: 1.5 },
  });
const monsterDebris = (assets: readonly string[], sizeScale: number = 1): readonly SpriteClip[] =>
  assets.map(asset => clip([asset], sizeScale));

function monsterDirections(frames: MonsterFrameSet): ActorVisualDefinition["directions"] {
  return Object.fromEntries(
    Object.entries(frames).map(([direction, directionalFrames]) => [direction, {
      normal: clip(directionalFrames.normal),
      ...(directionalFrames.walk
        ? { walk: clip(directionalFrames.walk, 1, undefined, 125, { loop: true }) }
        : {}),
      ...(directionalFrames.melee
        ? { melee: clip(directionalFrames.melee, 1, undefined, 125, { eventFrame: 2 }) }
        : {}),
      ...(directionalFrames.ranged
        ? { ranged: clip(directionalFrames.ranged, 1, undefined, 125, { eventFrame: 2 }) }
        : {}),
    }]),
  ) as Record<SpriteDirection, ActorVisualDefinition["directions"][string]>;
}

